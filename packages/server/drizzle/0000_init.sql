-- Every ledger write moves the account's balance, in the same transaction.
-- The balance CHECK fires on this UPDATE, so an entry that would take a
-- player below zero fails, and with it the whole transaction.
CREATE FUNCTION "kauda_apply_entry"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE "accounts" SET "balance" = "balance" + NEW."chips" WHERE "id" = NEW."account_id";
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ledger entry for unknown account %', NEW."account_id";
  END IF;
  RETURN NEW;
END;
$$;
