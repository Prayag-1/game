-- At commit, the books must balance: the entries of every round sum to 0,
-- and every account, the mint included, sums to 0. Deferred, so a
-- transaction may write its entries in any order.
CREATE FUNCTION "kauda_check_books"() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  total numeric;
BEGIN
  IF NEW."round_id" IS NOT NULL THEN
    SELECT COALESCE(SUM("chips"), 0) INTO total FROM "ledger_entries" WHERE "round_id" = NEW."round_id";
    IF total <> 0 THEN
      RAISE EXCEPTION 'round % does not balance: its entries sum to %', NEW."round_id", total;
    END IF;
  END IF;
  SELECT COALESCE(SUM("balance"), 0) INTO total FROM "accounts";
  IF total <> 0 THEN
    RAISE EXCEPTION 'the books do not balance: all accounts sum to %', total;
  END IF;
  RETURN NULL;
END;
$$;
